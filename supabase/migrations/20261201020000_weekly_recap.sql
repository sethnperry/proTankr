-- Weekly Recap: one report a week for admin and dispatch (how well each driver used the week's time, and where the
-- delays came from). Settings, the stored weekly snapshots, and a change log for the time allowances.

create table if not exists public.weekly_recap_settings (
  company_id uuid primary key,
  enabled boolean not null default false,              -- the standing Monday email
  recipients text[] not null default '{}',
  tz text not null default 'America/New_York',
  send_at text not null default '04:00',
  last_for_week date,                                   -- the Monday of the last week generated by the schedule
  allowances jsonb not null default '{}',               -- overrides of the defaults in lib/recap/types.ts
  version int not null default 1,                       -- bumped on every change to allowances
  updated_by uuid,
  updated_at timestamptz not null default now()
);

create table if not exists public.weekly_recaps (
  company_id uuid not null,
  week_start date not null,                             -- the Monday
  standards_version text not null,
  settings_version int not null default 1,
  generated_at timestamptz not null default now(),
  generated_by uuid,                                    -- null = the schedule
  regenerated_at timestamptz,
  report jsonb not null,
  primary key (company_id, week_start)
);

create table if not exists public.weekly_recap_settings_log (
  log_id uuid primary key default gen_random_uuid(),
  company_id uuid not null,
  changed_by uuid,
  changed_at timestamptz not null default now(),
  old_value jsonb,
  new_value jsonb
);

alter table public.weekly_recap_settings enable row level security;
alter table public.weekly_recaps enable row level security;
alter table public.weekly_recap_settings_log enable row level security;

-- Admin and dispatch (and ProTankr super admins) read; lead drivers and drivers never do.
create or replace function public.can_read_weekly_recap(p_company_id uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_super_admin() or exists (
    select 1 from public.user_companies uc
    where uc.company_id = p_company_id and uc.user_id = auth.uid() and uc.role in ('owner', 'admin', 'dispatch')
  );
$$;
grant execute on function public.can_read_weekly_recap(uuid) to authenticated;

drop policy if exists weekly_recaps_read on public.weekly_recaps;
create policy weekly_recaps_read on public.weekly_recaps for select using (public.can_read_weekly_recap(company_id));
drop policy if exists weekly_recap_settings_read on public.weekly_recap_settings;
create policy weekly_recap_settings_read on public.weekly_recap_settings for select using (public.can_read_weekly_recap(company_id));
drop policy if exists weekly_recap_settings_log_read on public.weekly_recap_settings_log;
create policy weekly_recap_settings_log_read on public.weekly_recap_settings_log for select using (public.can_read_weekly_recap(company_id));
-- Writes go through the server (service role): settings changes are logged there.
